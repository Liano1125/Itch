import Foundation

/// Durable lifecycle states for one isolated V3 → V4 migration attempt.
/// This type deliberately contains no filesystem paths or user payloads.
enum V4MigrationJournalState: String, Codable, CaseIterable {
    case requested
    case snapshotting
    case snapshotReady
    case stagingCreated
    case converting
    case verifying
    case manifestWritten
    case stagingValidated
    case eligibleForIndependentSafetyGates
    case failed
    case abandoned
    case superseded

    var isTerminal: Bool {
        switch self {
        case .eligibleForIndependentSafetyGates, .failed, .abandoned, .superseded:
            return true
        default:
            return false
        }
    }
}

/// Stable, privacy-safe event emitted for each accepted state transition.
struct V4MigrationJournalEvent: Codable, Equatable, Identifiable {
    let runID: String
    let sequence: Int
    let fromState: V4MigrationJournalState?
    let toState: V4MigrationJournalState
    let code: String
    let timestamp: Date

    var id: String { "\(runID):\(sequence)" }
}

/// Pure transition policy. Persistence and atomic event appends belong to a
/// separate repository implementation.
enum V4MigrationJournalStateMachine {
    static func canTransition(
        from current: V4MigrationJournalState?,
        to next: V4MigrationJournalState
    ) -> Bool {
        guard let current else {
            return next == .requested
        }
        guard !current.isTerminal else { return false }

        if next == .failed || next == .abandoned {
            return true
        }

        switch (current, next) {
        case (.requested, .snapshotting),
             (.snapshotting, .snapshotReady),
             (.snapshotReady, .stagingCreated),
             (.stagingCreated, .converting),
             (.converting, .verifying),
             (.verifying, .manifestWritten),
             (.manifestWritten, .stagingValidated),
             (.stagingValidated, .eligibleForIndependentSafetyGates):
            return true
        case (.snapshotReady, .superseded),
             (.stagingCreated, .superseded),
             (.converting, .superseded),
             (.verifying, .superseded),
             (.manifestWritten, .superseded),
             (.stagingValidated, .superseded):
            return true
        default:
            return false
        }
    }
}

/// Privacy-safe current journal snapshot. Opaque IDs are generated by the
/// storage layer; no absolute paths, credentials, or source payloads belong here.
struct V4MigrationJournalRecord: Codable, Equatable, Identifiable {
    let journalVersion: Int
    let runID: String
    let idempotencyKey: String
    let state: V4MigrationJournalState
    let sourceSchemaVersion: String
    let sourceSnapshotID: String?
    let sourceSnapshotDigest: String?
    let sourceInventoryDigest: String?
    let destinationSchemaVersion: String
    let stagingStoreID: String?
    let completedDomains: [String]
    let manifestDigest: String?
    let createdAt: Date
    let updatedAt: Date
    let attemptNumber: Int
    let failureCode: String?

    static let currentJournalVersion = 1

    var id: String { runID }

    init(
        runID: String,
        idempotencyKey: String,
        sourceSchemaVersion: String,
        destinationSchemaVersion: String,
        createdAt: Date,
        attemptNumber: Int = 1,
        stagingStoreID: String? = nil
    ) {
        self.journalVersion = Self.currentJournalVersion
        self.runID = runID
        self.idempotencyKey = idempotencyKey
        self.state = .requested
        self.sourceSchemaVersion = sourceSchemaVersion
        self.sourceSnapshotID = nil
        self.sourceSnapshotDigest = nil
        self.sourceInventoryDigest = nil
        self.destinationSchemaVersion = destinationSchemaVersion
        self.stagingStoreID = stagingStoreID
        self.completedDomains = []
        self.manifestDigest = nil
        self.createdAt = createdAt
        self.updatedAt = createdAt
        self.attemptNumber = attemptNumber
        self.failureCode = nil
    }

    private init(
        journalVersion: Int,
        runID: String,
        idempotencyKey: String,
        state: V4MigrationJournalState,
        sourceSchemaVersion: String,
        sourceSnapshotID: String?,
        sourceSnapshotDigest: String?,
        sourceInventoryDigest: String?,
        destinationSchemaVersion: String,
        stagingStoreID: String?,
        completedDomains: [String],
        manifestDigest: String?,
        createdAt: Date,
        updatedAt: Date,
        attemptNumber: Int,
        failureCode: String?
    ) {
        self.journalVersion = journalVersion
        self.runID = runID
        self.idempotencyKey = idempotencyKey
        self.state = state
        self.sourceSchemaVersion = sourceSchemaVersion
        self.sourceSnapshotID = sourceSnapshotID
        self.sourceSnapshotDigest = sourceSnapshotDigest
        self.sourceInventoryDigest = sourceInventoryDigest
        self.destinationSchemaVersion = destinationSchemaVersion
        self.stagingStoreID = stagingStoreID
        self.completedDomains = completedDomains
        self.manifestDigest = manifestDigest
        self.createdAt = createdAt
        self.updatedAt = updatedAt
        self.attemptNumber = attemptNumber
        self.failureCode = failureCode
    }

    func transitioning(
        to next: V4MigrationJournalState,
        at date: Date,
        sequence: Int,
        code: String
    ) throws -> (record: V4MigrationJournalRecord, event: V4MigrationJournalEvent) {
        guard V4MigrationJournalStateMachine.canTransition(from: state, to: next) else {
            throw TransitionError.invalidTransition
        }
        guard sequence > 0 else { throw TransitionError.invalidSequence }
        guard Self.isSafeCode(code) else {
            throw TransitionError.invalidDiagnosticCode
        }

        let updated = V4MigrationJournalRecord(
            journalVersion: journalVersion,
            runID: runID,
            idempotencyKey: idempotencyKey,
            state: next,
            sourceSchemaVersion: sourceSchemaVersion,
            sourceSnapshotID: sourceSnapshotID,
            sourceSnapshotDigest: sourceSnapshotDigest,
            sourceInventoryDigest: sourceInventoryDigest,
            destinationSchemaVersion: destinationSchemaVersion,
            stagingStoreID: stagingStoreID,
            completedDomains: completedDomains,
            manifestDigest: manifestDigest,
            createdAt: createdAt,
            updatedAt: date,
            attemptNumber: attemptNumber,
            failureCode: next == .failed ? code : failureCode
        )
        let event = V4MigrationJournalEvent(
            runID: runID,
            sequence: sequence,
            fromState: state,
            toState: next,
            code: code,
            timestamp: date
        )
        return (updated, event)
    }

    private static func isSafeCode(_ value: String) -> Bool {
        guard !value.isEmpty, value.count <= 96 else { return false }
        return value.unicodeScalars.allSatisfy {
            CharacterSet(charactersIn: "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789._-").contains($0)
        }
    }

    enum TransitionError: Error, Equatable {
        case invalidTransition
        case invalidDiagnosticCode
        case invalidSequence
    }
}
